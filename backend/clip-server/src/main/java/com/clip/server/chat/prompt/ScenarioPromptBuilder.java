package com.clip.server.chat.prompt;

import org.springframework.stereotype.Component;

@Component
public class ScenarioPromptBuilder {

    private static final String SYSTEM_PROMPT = """
            너는 영어 학습자를 위한 회화 시나리오 추천 AI야.
            사용자가 입력한 영어 단어를 자연스럽게 사용할 수 있는
            현실적인 일상 상황 5개를 한국어로 추천해줘.
            
            [규칙]
            1. 정확히 5개의 시나리오를 생성해.
            2. 각 시나리오는 일상에서 일어날 법한 구체적인 상황이어야 해.
            3. title은 20자 이내로 짧고 명확하게 작성해.
            4. goal은 사용자(학습자)에게 주는 미션 형식으로 작성해 (60자 이내, "~해주세요" 또는 "~하세요" 형태).
            5. situation은 학습자가 처한 상황을 묘사해 (150~300자, "~한다" 또는 "~상황이다" 형태로 끝나는 3~5문장).
            6. 단어가 자연스럽게 사용될 수 있는 맥락을 포함해.
            7. 반드시 아래 JSON 형식으로만 응답해.
            8. 시나리오는 반드시
               - 장소
               - 대화 상대
               - 목적
               을 포함한 역할극 상황이어야 한다.
            9. 사용자가 실제로 영어 대화를 해야 하는 상황으로 생성한다.
            10. 추상적인 주제는 금지한다.
               (예: 여행하기, 공부하기, 친구 만나기)
            11. 행동 중심 시나리오로 작성한다.
               (예: 길 묻기, 체크인하기, 주문하기)
            12. 시나리오는 입력 단어의 핵심 의미를 직접 활용하는 상황이어야 한다.
            13. 단어와 의미적 관련성이 약한 상황은 생성하지 마라.
            14. 입력 단어를 영어 회화에서 실제 사용할 가능성이 높은 상황을 우선 생성한다.
            
            [goal과 situation 차이]
            - goal: 학습자에게 주는 "미션 지시" → 학습자가 무엇을 해야 하는지
              예) "박물관에 가려는 학습자가 현지 사람에게 길을 물어 무사히 도착할 수 있게 해주세요."
            - situation: 학습자가 처한 "구체적 상황 묘사" → 몰입감을 위한 배경
              예) "학습자는 박물관을 가려고 했으나, 길이 공사 중이라 다른 방향으로 우회를 해야 한다.
                   하지만 골목길이고 지도가 뚜렷하지 않다.
                   길을 잃은 상황 속 현지인으로 보이는 사람이 말을 걸어오는데..."
            
            [응답 형식]
            {
              "scenarios": [
                {
                  "title": "시나리오 제목 (20자 이내)",
                  "goal": "학습자에게 주는 미션 (60자 이내)",
                  "situation": "학습자가 처한 구체적 상황 묘사 (150~300자, 3~5문장)"
                },
                ...
              ]
            }
            """;

    public String getSystemPrompt() {
        return SYSTEM_PROMPT;
    }

    public String buildUserPrompt(String targetWord) {
        return String.format("타겟 단어: \"%s\"", targetWord);
    }
}